<p>This website is the online record of the Mogul Shiah Muslim Burial Ground in Yangon, whose gate carries the year 1996. It helps families, relatives and friends find the resting place of a loved one and visit with ease.</p>

<h2>What you can do here</h2>
<ul>
  <li>Search by name, in English, Burmese or Arabic.</li>
  <li>See the section, plot and grave number of each grave.</li>
  <li>Get directions on Google Maps.</li>
  <li>Scan a QR code to open a record directly.</li>
  <li>Read the site in English or Burmese.</li>
</ul>

