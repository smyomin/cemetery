<h2>Your privacy</h2>
<p>Only basic details such as names, dates, age and the location of the grave are shown publicly. The contact details of families are never shown. A photo of a person is shown only with the family's permission. To ask for a correction or for a record to be removed, please contact the committee through the <a href="/en/page/contact">Contact</a> page.</p>

<h2>Visiting</h2>
<p>We ask every visitor to treat the grounds with respect. You can read the rules and visiting hours on the <a href="/en/page/rules-and-hours">Rules and visiting hours</a> page.</p>